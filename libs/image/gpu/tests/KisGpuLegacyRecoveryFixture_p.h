// Emits earlier records for the maintained legacy reader contracts.
inline QByteArray legacyRecovery(const OperationDocument &document, quint8 format)
{
    auto payload = document.recoveryData().chopped(32);
    if (format < 40) {
        // Format 40 adds the current selection rectangle after savedRevision.
        QByteArray selection;
        QDataStream header(&payload, QIODevice::ReadOnly);
        header.setVersion(QDataStream::Qt_5_15);
        header.setByteOrder(QDataStream::BigEndian);
        quint32 magic = 0;
        quint16 version = 0;
        qint32 width = 0, height = 0;
        quint64 nextRevision = 0, nextOperation = 0, nextLayer = 0, savedRevision = 0;
        header >> magic >> version >> width >> height >> nextRevision >> nextOperation >> nextLayer >> savedRevision;
        Q_ASSERT(magic == 0x4c504f52 && version == 40);
        payload.remove(int(header.device()->pos()), 16);
    }
    auto versions = document.historyVersions();
    if (format < 41) {
        for (const auto &version : document.historyVersions()) {
            QByteArray prefix;
            QDataStream stream(&prefix, QIODevice::WriteOnly);
            stream.setVersion(QDataStream::Qt_5_15);
            stream.setByteOrder(QDataStream::BigEndian);
            stream << qint32(version->size.width()) << qint32(version->size.height());
            for (const auto component : version->projectionBackground) stream << component;
            const bool explicitSelection = version->selectedLayers.size() > 1 ||
                (!version->selectedLayers.isEmpty() && version->selectedLayers.first() != version->activeLayer);
            stream << version->revision() << version->historyRevision() << version->activeLayer
                   << (quint32(version->layers.size()) | (explicitSelection ? 0x80000000u : 0u));
            const auto offset = payload.indexOf(prefix);
            Q_ASSERT(offset >= 0 && offset == payload.lastIndexOf(prefix));
            qsizetype selectionOffset = offset + prefix.size();
            if (explicitSelection) {
                QDataStream selected(payload.mid(selectionOffset, 4));
                selected.setVersion(QDataStream::Qt_5_15);
                selected.setByteOrder(QDataStream::BigEndian);
                quint32 count = 0;
                selected >> count;
                selectionOffset += 4 + qsizetype(count) * 8;
            }
            payload.remove(selectionOffset, 16);
        }
    }
    if (format < 27) {
        for (int i = 0; i < versions.size(); ++i) {
            const auto &version = versions[i];
            Q_ASSERT(version->size == document.snapshot()->size && !document.historyCanvasResize(i));
            QByteArray prefix;
            QDataStream stream(&prefix, QIODevice::WriteOnly);
            stream.setVersion(QDataStream::Qt_5_15);
            stream.setByteOrder(QDataStream::BigEndian);
            stream << qint32(version->size.width()) << qint32(version->size.height());
            for (const auto component : version->projectionBackground) stream << component;
            const bool selection = version->selectedLayers.size() > 1 ||
                (!version->selectedLayers.isEmpty() && version->selectedLayers.first() != version->activeLayer);
            stream << version->revision() << version->historyRevision() << version->activeLayer
                   << (quint32(version->layers.size()) | (selection ? 0x80000000u : 0u));
            const auto offset = payload.indexOf(prefix);
            Q_ASSERT(offset >= 0 && offset == payload.lastIndexOf(prefix));
            payload.remove(offset, 8);
        }
    }
    versions.append(document.preview());
    if (format < 34) {
        QSet<QByteArray> records;
        for (const auto &version : versions) {
            if (!version) continue;
            for (const auto &layer : version->layers) {
                Q_ASSERT(format >= 30 || layer.colorLabelIndex == 0);
                Q_ASSERT(format >= 31 || layer.projectionChannelMask == 15);
                Q_ASSERT(format >= 33 || !layer.passThrough);
                Q_ASSERT(layer.blendMode == LayerBlendMode::Normal);
                Q_ASSERT(format >= 29 || (layer.kind == LayerKind::Paint && layer.parentUuid.isNull()));
                Q_ASSERT(format >= 24 || layer.position.isNull());
                QByteArray record;
                QDataStream stream(&record, QIODevice::WriteOnly);
                stream.setVersion(QDataStream::Qt_5_15);
                stream.setByteOrder(QDataStream::BigEndian);
                const auto name = layer.name.toUtf8();
                stream << layer.id << quint32(name.size());
                stream.writeRawData(name.constData(), name.size());
                stream << quint8(layer.visible) << layer.uuid;
                for (const auto component : layer.defaultPixel) stream << component;
                stream << layer.opacity << quint8(layer.userLocked)
                       << quint8(quint8(layer.pinnedToTimeline) | ((15u ^ layer.channelWriteMask) << 1));
                const auto positionOffset = record.size();
                stream << qint32(layer.position.x()) << qint32(layer.position.y());
                const auto hierarchyOffset = record.size();
                stream << quint8(layer.kind) << layer.parentUuid;
                const auto labelOffset = record.size();
                stream << qint32(layer.colorLabelIndex);
                const auto projectionOffset = record.size();
                stream << layer.projectionChannelMask;
                const auto passThroughOffset = record.size();
                stream << quint8(layer.passThrough);
                const auto blendModeOffset = record.size();
                stream << quint8(layer.blendMode);
                if (records.contains(record)) continue;
                records.insert(record);
                qsizetype next = 0;
                for (;;) {
                    const auto found = payload.indexOf(record, next);
                    if (found < 0) break;
                    const auto offset = format < 24 ? positionOffset : format < 29 ? hierarchyOffset : format < 30 ? labelOffset :
                        format < 31 ? projectionOffset : format < 33 ? passThroughOffset : blendModeOffset;
                    payload.remove(found + offset, record.size() - offset);
                    next = found + offset;
                }
            }
        }
    }
    QSet<QPair<quint64, quint64>> seen;
    for (const auto &version : versions) {
        if (!version) continue;
        for (const auto &layer : version->layers) {
            for (const auto &value : layer.operations) {
                const auto paint = std::get_if<PaintSnapshot>(&value);
                if (!paint) continue;
                const auto &operation = **paint;
                const QPair<quint64, quint64> key(operation.id.sequence, operation.version);
                if (seen.contains(key)) continue;
                seen.insert(key);
                Q_ASSERT(format >= 19 || !operation.brush.pixelPerfect);
                Q_ASSERT(!operation.brush.basicSmoothing);
                Q_ASSERT(!operation.brush.weightedSmoothing);
                Q_ASSERT(!operation.brush.gaussianWash);
                Q_ASSERT(format >= 18 || operation.shape.kind != ShapeKind::Path);
                Q_ASSERT(format >= 17 || (operation.figureStyle.outline && !operation.figureStyle.fill));
                QByteArray prefix;
                QDataStream stream(&prefix, QIODevice::WriteOnly);
                stream.setVersion(QDataStream::Qt_5_15);
                stream.setByteOrder(QDataStream::BigEndian);
                stream.setFloatingPointPrecision(QDataStream::DoublePrecision);
                stream << quint8(0) << operation.id.sequence << operation.version << operation.layer;
                for (const auto component : operation.brush.rgba) stream << component;
                stream << operation.brush.diameter << operation.brush.spacing << operation.brush.opacity
                       << quint8(quint8(operation.brush.erase) | (quint8(operation.brush.alphaLocked) << 1) |
                                 ((15u ^ operation.brush.channelWriteMask) << 2) |
                                 (quint8(operation.brush.mirrorHorizontal) << 6) | (quint8(operation.brush.mirrorVertical) << 7));
                if (operation.brush.mirrorHorizontal || operation.brush.mirrorVertical)
                    stream << qint32(operation.brush.mirrorCenter.x()) << qint32(operation.brush.mirrorCenter.y());
                const auto gaussianOffset = prefix.size();
                stream << quint8(0);
                stream << operation.randomSeed << quint8(operation.shape.kind)
                       << operation.shape.first.x() << operation.shape.first.y()
                       << operation.shape.second.x() << operation.shape.second.y() << operation.shape.rotation;
                if (operation.shape.kind == ShapeKind::RoundedRectangle)
                    stream << operation.shape.cornerRadii.width() << operation.shape.cornerRadii.height();
                qsizetype pathCallsOffset = -1;
                if (operation.shape.kind == ShapeKind::Path) {
                    stream << quint8(operation.shape.windingFill) << quint32(operation.shape.pathCommands.size());
                    for (const auto command : operation.shape.pathCommands) stream << quint8(command);
                    Q_ASSERT(operation.shape.pathCalls.isEmpty());
                    pathCallsOffset = prefix.size();
                    stream << quint32(0);
                }
                const auto position = payload.indexOf(prefix);
                Q_ASSERT(position >= 0 && position == payload.lastIndexOf(prefix));
                const auto styleSize = 1 + (operation.figureStyle.fill ? 4 : 0);
                Q_ASSERT(payload.at(position + prefix.size() + styleSize) == char(operation.brush.pixelPerfect));
                if (format < 40) {
                    // Format 40 appends the selection rectangle after the samples.
                    const auto samples = position + prefix.size() + styleSize + 1 + 4;
                    payload.remove(samples + qsizetype(operation.sampleCount) * 64, 16);
                }
                if (format < 21) {
                    const auto samples = position + prefix.size() + styleSize + 1 + 4;
                    for (qsizetype index = operation.sampleCount; index > 0; --index)
                        payload.remove(samples + (index - 1) * 64 + 56, 8);
                }
                if (format < 19) payload.remove(position + prefix.size() + styleSize, 1);
                if (format < 17) payload.remove(position + prefix.size(), styleSize);
                if (format < 39 && pathCallsOffset >= 0) payload.remove(position + pathCallsOffset, 4);
                if (format < 38) payload.remove(position + gaussianOffset, 1);
            }
        }
    }
    payload[4] = 0;
    payload[5] = char(format);
    payload.append(QCryptographicHash::hash(payload, QCryptographicHash::Sha256));
    return payload;
}
